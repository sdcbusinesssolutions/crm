/**
 * Super Admin Action: Generate a magic login link for a Tenant Admin
 * POST /api/admin/auth/impersonate-admin
 * Body: { targetDomain: 'chatmat.in' }
 */
exports.impersonateTenantAdmin = async (req, res) => {
    try {
        const { targetDomain } = req.body;
        const requesterDomain = req.admin.managed_domain; // From verifyAdminToken middleware

        // 1. Verify Super Admin Status
        const MASTER_DOMAIN = process.env.VITE_MASTER_URL ? new URL(process.env.VITE_MASTER_URL).hostname : 'clickube.com';
        // Allow localhost super admin too
        const isSuperAdmin = requesterDomain === MASTER_DOMAIN || requesterDomain === 'localhost' || requesterDomain === '127.0.0.1';

        if (!isSuperAdmin) {
            return res.status(403).json({ message: 'Access Denied: Only Super Admin can impersonate other admins.' });
        }

        if (!targetDomain) {
            return res.status(400).json({ message: 'Target domain is required.' });
        }

        console.log(`[SuperAdmin] Generating Admin Impersonation Link for: ${targetDomain}`);

        // 2. Generate details
        const targetEmail = `Admin@${targetDomain}`;

        // 3. Create Short-Lived Exchange Token (5 minutes)
        const impersonationToken = jwt.sign({
            is_impersonation: true,
            email: targetEmail,
            target_domain: targetDomain,
            generated_by: req.admin.email
        }, process.env.JWT_SECRET || 'secret', { expiresIn: '5m' });

        // 4. Construct URL
        // Requires valid DNS/Routing setup. 
        // We redirect to the Target Domain's Admin Login page with the token
        const protocol = targetDomain.includes('localhost') ? 'http' : 'https';
        const redirectUrl = `${protocol}://${targetDomain}/admin/auth/login?token=${impersonationToken}`;

        res.json({
            success: true,
            url: redirectUrl,
            message: `Generated impersonation link for ${targetDomain}`
        });

    } catch (err) {
        console.error('Impersonate Admin Error:', err);
        res.status(500).json({ message: 'Internal Server Error' });
    }
};
