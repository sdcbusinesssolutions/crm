const AdminModel = require('../../models/admin/AdminModel');
const jwt = require('jsonwebtoken');

exports.loginAdmin = async (req, res) => {
    const { email, password } = req.body;

    // MULTI-TENANCY CHECK:
    // Determine the expected admin email for this specific domain
    const origin = req.headers.origin || req.headers.host || '';
    let currentDomain = 'localhost';
    try {
        if (origin.startsWith('http')) {
            currentDomain = new URL(origin).hostname;
        } else {
            currentDomain = origin.split(':')[0];
        }
    } catch (e) { }

    // Check if this is a local request BEFORE we overwrite currentDomain
    const isLocalRequest = currentDomain.includes('localhost') || currentDomain.includes('127.0.0.1');

    // Allow fallback to env DOMAIN if localhost
    if (isLocalRequest) {
        currentDomain = process.env.DOMAIN || 'clickube.com';
    }

    // Expected format: Admin@clickube.com, Admin@chatmat.in
    const expectedAdminEmail = `Admin@${currentDomain}`;

    // Strict Match: Admin@chatmat.in cannot login to clickube.com dashboard
    // If they try to use Admin@clickube.com on chatmat.in, this logic blocks it because 
    // we strictly check against the Dynamic Domain Email.

    // 1. Check if this is an Impersonation Login (Token Exchange)
    const { impersonation_token } = req.body;
    if (impersonation_token) {
        try {
            // Verify the short-lived token generated by Super Admin
            const decoded = jwt.verify(impersonation_token, process.env.JWT_SECRET || 'secret');

            // Ensure this is an impersonation token
            if (!decoded.is_impersonation) {
                return res.status(401).json({ message: 'Invalid token type' });
            }

            console.log(`[Admin] Impersonation Login Success: ${decoded.email} on ${decoded.target_domain}`);

            let targetUserId = 'admin-' + decoded.target_domain;
            
            // Try to find the true UUID of the impersonated user to support wallet lookups
            const { supabaseAdmin } = require('../../lib/supabaseClient');
            if (supabaseAdmin) {
                const { data: profile } = await supabaseAdmin
                    .from('profiles')
                    .select('id')
                    .eq('email', decoded.email)
                    .single();
                if (profile && profile.id) {
                    targetUserId = profile.id;
                }
            }

            // Issue a standard session token (Long Lived) for the target admin
            const token = jwt.sign({
                id: targetUserId,
                user_id: targetUserId,
                email: decoded.email,
                managed_domain: decoded.target_domain
            }, process.env.JWT_SECRET || 'secret', { expiresIn: '1d' });

            return res.json({ token, admin: { email: decoded.email, name: 'Tenent Administrator', domain: decoded.target_domain } });

        } catch (err) {
            console.error('Impersonation Token Error:', err.message);
            return res.status(401).json({ message: 'Invalid or expired impersonation token' });
        }
    }

    // A. Standard Password Login Logic
    // 1. Check Demo Credentials (Dynamic)
    const isStandardMatch = email.toLowerCase() === expectedAdminEmail.toLowerCase();
    const isLocalMatch = isLocalRequest && email.toLowerCase() === 'admin@localhost.com';

    if ((isStandardMatch || isLocalMatch) && password === 'Admin@12345') {

        let role = 'admin'; // Default role
        let adminName = 'Administrator';
        let fetchedAdminId = null;

        // SECURITY CHECK & ROLE ENRICHMENT
        const { supabaseAdmin } = require('../../lib/supabaseClient'); // Lazy load
        if (supabaseAdmin) {
            // Check if a user exists with this email
            const { data: { users }, error } = await supabaseAdmin.auth.admin.listUsers();
            if (users) {
                const adminUser = users.find(u => u.email.toLowerCase() === email.toLowerCase());
                if (adminUser) {
                    fetchedAdminId = adminUser.id;
                    const isBanned = adminUser.banned_until && new Date(adminUser.banned_until) > new Date();
                    if (isBanned) {
                        console.warn(`[Blocked Login] Banned Admin tried to login: ${email}`);
                        return res.status(403).json({ message: 'This Admin Account has been suspended by Super Admin.' });
                    }

                    // Fetch Profile for Role
                    const { data: profile } = await supabaseAdmin
                        .from('profiles')
                        .select('role, full_name, name')
                        .eq('id', adminUser.id)
                        .single();

                    if (profile) {
                        role = profile.role || role;
                        adminName = profile.full_name || profile.name || adminName;
                    }
                }
            }
        }

        const tokenPayload = {
            id: fetchedAdminId || ('admin-' + currentDomain),
            user_id: fetchedAdminId || ('admin-' + currentDomain),
            email,
            managed_domain: currentDomain,
            role: role // Embed dynamic role
        };

        const token = jwt.sign(tokenPayload, process.env.JWT_SECRET || 'secret', { expiresIn: '1d' });

        return res.json({ token, admin: { email, name: adminName, domain: currentDomain, role } });
    }

    // 2. (Optional) Supabase Database Logic
    // If the hardcoded check fails, we check against the real Supabase Auth
    try {
        const { supabase, supabaseAdmin } = require('../../lib/supabaseClient');

        // A. Authenticate with Supabase Auth (Checks password)
        const { data: authData, error: authError } = await supabase.auth.signInWithPassword({
            email,
            password
        });

        if (authError || !authData.user) {
            console.warn(`[Admin Login Failed] Supabase Auth failed for ${email}: ${authError?.message}`);
            return res.status(401).json({ message: 'Invalid credentials or incorrect domain.' });
        }

        // B. Fetch User Profile to check Role and Domain
        // We use supabaseAdmin to bypass RLS and ensure we see the true record
        const { data: profile } = await supabaseAdmin
            .from('profiles')
            .select('*')
            .eq('id', authData.user.id)
            .single();

        if (!profile) {
            return res.status(401).json({ message: 'User profile not found.' });
        }

        // C. Validate Role (Must be 'admin')
        if (profile.role !== 'admin') {
            return res.status(403).json({ message: 'Access Denied: You are not an Administrator.' });
        }

        // D. Validate Domain Match
        // Normalize domains
        const normalize = (d) => d ? d.trim().toLowerCase().replace(/^www\./, '') : '';
        const normAssigned = normalize(profile.signup_domain);
        const normCurrent = normalize(currentDomain);

        // Use the preserved isLocalRequest check
        if (normAssigned !== normCurrent && !isLocalRequest) {
            console.warn(`[Admin Login Blocked] Domain Mismatch. Assigned: ${normAssigned}, Current: ${normCurrent}, IsLocal: ${isLocalRequest}`);
            return res.status(403).json({ message: 'Invalid Domain: You cannot access this dashboard.' });
        }

        // E. Success - Generate the Custom JWT used by this Admin Backend
        const token = jwt.sign({
            id: profile.id,
            user_id: profile.id,
            email: profile.email,
            managed_domain: normAssigned,
            role: profile.role,
            is_supabase_user: true
        }, process.env.JWT_SECRET || 'secret', { expiresIn: '1d' });

        console.log(`[Admin Login Success] ${email} logged in to ${currentDomain} (User ID: ${profile.id})`);

        return res.json({
            token,
            admin: {
                email: profile.email,
                name: profile.full_name || 'Administrator',
                domain: normAssigned,
                role: profile.role
            }
        });

    } catch (dbError) {
        console.error("Supabase Login Logic Error:", dbError);
        // Fallthrough to generic error
    }

    console.warn(`[Admin Login Failed] Attempt: ${email} on domain ${currentDomain}`);
    res.status(401).json({ message: 'Invalid credentials or incorrect domain.' });
};

