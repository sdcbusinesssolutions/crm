CREATE TABLE IF NOT EXISTS public.sheet_automation_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  automation_id UUID REFERENCES public.sheet_automations(id) ON DELETE CASCADE,
  row_hash TEXT NOT NULL,
  phone_number TEXT,
  status TEXT DEFAULT 'pending', -- pending, sent, failed
  sent_at TIMESTAMPTZ DEFAULT NOW(),
  meta JSONB
);

-- Index for faster lookups
CREATE INDEX IF NOT EXISTS idx_sheet_history_auto_hash ON public.sheet_automation_history(automation_id, row_hash);
